# 2. VALIDATE CONFIG
# ──────────────────────────────────────────────
echo ""
echo "╔══════════════════════════════════════════╗"
echo "║    SUTRA Deployment — Pre-flight Check   ║"
echo "╚══════════════════════════════════════════╝"

if [[ -z "$DOMAIN" ]]; then
  echo "❌ DOMAIN is not set."; exit 1
fi
if [[ "$GEMINI_API_KEY" == "your-key" ]]; then
  echo "❌ Please replace GEMINI_API_KEY with your actual key."; exit 1
