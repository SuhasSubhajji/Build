# Extract to a temp folder first, then copy into APP_DIR
TEMP_DIR=$(mktemp -d)
unzip -q "$ZIP_FILE" -d "$TEMP_DIR"

# Case 1: flat zip (SUTRA default) — package.json directly in root
# Case 2: wrapped zip — package.json inside a single subfolder
