  apps: [
    {
      name: 'sutra',
      script: 'server.ts',
      interpreter: 'node',
      interpreter_args: '--import tsx/esm',
      cwd: '${APP_DIR}',
      env_file: '${APP_DIR}/.env',
      env: {
        NODE_ENV: 'production',
        PORT: 3000,
      },
      instances: 1,
      autorestart: true,
      watch: false,
      max_memory_restart: '512M',
