if [[ -z "$EMAIL" ]]; then
  echo "❌ EMAIL is not set."; exit 1
fi

# ──────────────────────────────────────────────
# 3. FIND ZIP IN WORKING DIRECTORY
# ──────────────────────────────────────────────
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
