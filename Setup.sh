  cp -r "$TEMP_DIR"/. "$APP_DIR/"
else
  EXTRACTED_ROOT=$(find "$TEMP_DIR" -mindepth 1 -maxdepth 1 -type d | head -1)
  if [[ -n "$EXTRACTED_ROOT" && -f "$EXTRACTED_ROOT/package.json" ]]; then
    cp -r "$EXTRACTED_ROOT"/. "$APP_DIR/"
  else
    echo "❌ Could not locate package.json inside the zip. Is this the correct SUTRA zip?"
    rm -rf "$TEMP_DIR"
    exit 1
  fi
fi

